import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import MarkdownIt from 'markdown-it';
import hljs from 'highlight.js';
import YAML from 'yaml';
const here=path.dirname(fileURLToPath(import.meta.url));
const file=path.resolve(process.argv[2]);
if(!file.endsWith('.md'))throw new Error('Expected a Markdown note');
const source=await readFile(file,'utf8');
const match=source.match(/^---\n([\s\S]*?)\n---\n/);
if(!match)throw new Error('frontmatter required');
const meta=YAML.parse(match[1]);
const body=source.slice(match[0].length).trimStart();
const title=body.match(/^# (.*)/)[1];
const md=new MarkdownIt({html:false,highlight:(code,language)=>language&&hljs.getLanguage(language)?hljs.highlight(code,{language}).value:''});
const headings=[];const counts=new Map();
md.renderer.rules.heading_open=(tokens,i)=>{
 const t=tokens[i+1].content;
 let id=t.toLowerCase().replace(/[^\p{L}\p{N}_ -]/gu,'').replace(/ /g,'-');
 const count=counts.get(id)||0;counts.set(id,count+1);if(count)id+='-'+count;
 if(tokens[i].tag==='h2')headings.push({id,title:t});
 return `<${tokens[i].tag} id="${id}">`;
};
md.renderer.rules.table_open=()=>'<div class="table-wrap" tabindex="0" role="region" aria-label="가로 스크롤 가능한 비교 표"><table>\n';
md.renderer.rules.table_close=()=>'</table></div>\n';
let html=md.render(body.replace(/^# .*\n+/,''));
html=html.replace(/<p><img src="([^"]+)" alt="([^"]*)"><\/p>/g,(_,src,alt)=>`<figure><img src="${src}" alt="${alt}"><figcaption>${alt}</figcaption></figure>`);
const links=headings.map(h=>`<a href="#${h.id}">${h.title}</a>`).join('');
html=html.replace(/(<h2[^>]*>[\s\S]*?<\/h2>\n<p>[\s\S]*?<\/p>)/,`$1<details class="toc" open><summary>학습 목차</summary>${links}</details>`);
html=html.replace(/<h2 id="([^"]+)">/g,'</section><section id="$1"><h2>').replace(/^<\/section>/,'')+'</section>';
const esc=s=>md.utils.escapeHtml(String(s));
const css=await readFile(path.join(here,'style.css'),'utf8');
const out=`<!doctype html><html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="icon" href="data:,"><title>${esc(title)}</title><style>${css}</style></head><body><a class="skip" href="#content">본문으로 건너뛰기</a><aside class="side-nav" aria-label="학습 목차"><p>CSAPP DEBUGGING LAB</p>${links}</aside><div class="layout"><header class="hero"><p class="eyebrow">CSAPP · DEBUGGING NOTE · ${esc(meta.date)}</p><h1>${esc(title)}</h1><p>관측 → 가설 → 대조 실험 → 결정 → 검증.<br>실행 환경을 바꿔 syscall LAB의 관측 경로를 확인한 과정.</p></header><main id="content">${html}</main><footer><a href="${esc(path.basename(file))}">Markdown 원문</a> · 확인 기준일 ${esc(meta.date)} KST</footer></div></body></html>\n`;
await writeFile(file.replace(/\.md$/,'.html'),out);
console.log(`Rendered note: ${headings.length} sections`);
